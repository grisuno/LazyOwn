        if arg == "options":
            if self._active_module is None:
                print_msg("No active module. Use 'use <module>' first.")
                return
            print(_format_module_detail(self._active_module))
            return

        rendered = _format_payload(self.params)
        if rendered:
            print_msg(rendered)

