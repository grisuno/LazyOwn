#!/usr/bin/env bash
# Regenerate the LazyOwn dependency lock files from pyproject.toml.
#
# pyproject.toml is the single source of truth. The locks are produced by
# resolving it in CLEAN virtualenvs, never by `pip freeze` of a working
# environment (which captures unrelated packages and un-resolvable pins).
#
#   requirements-light.txt  base only, resolved as a strict subset of full
#   requirements.txt        .[analytics,ai,cloud,rag] (full core, no ML)
#   requirements-ml.txt     the .[ml] additions on top of the full lock
#
# Usage: bash scripts/regen_locks.sh [python]
# Requires network access and a Python matching requires-python in pyproject.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PYTHON="${1:-python3}"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

cd "$ROOT"

mkvenv() {
    "$PYTHON" -m venv "$1"
    "$1/bin/pip" install --quiet --upgrade pip
}

freeze() {
    "$1/bin/pip" freeze --exclude-editable | grep -ivE '^lazyown(==| @)' | sort -f
}

echo "[*] Resolving full core (.[analytics,ai,cloud,rag]) ..."
mkvenv "$WORK/full"
"$WORK/full/bin/pip" install --quiet ".[analytics,ai,cloud,rag]"
"$WORK/full/bin/pip" check
{
    echo "# requirements.txt"
    echo "# Full core lock (shell + C2 + recon/exploit + analytics + AI + cloud + RAG)."
    echo "# Regenerated by scripts/regen_locks.sh from pyproject.toml; do not hand-edit."
    echo "# Light subset: requirements-light.txt. Heavy ML stack: requirements-ml.txt."
    echo ""
    freeze "$WORK/full"
} > requirements.txt

echo "[*] Resolving light base (constrained to full) ..."
mkvenv "$WORK/light"
"$WORK/light/bin/pip" install --quiet . -c requirements.txt
"$WORK/light/bin/pip" check
{
    echo "# requirements-light.txt"
    echo "# Light profile: shell + C2 + recon/exploit core. Strict subset of"
    echo "# requirements.txt at identical versions. Excludes analytics, AI, cloud,"
    echo "# RAG and ML. Regenerated by scripts/regen_locks.sh; do not hand-edit."
    echo ""
    freeze "$WORK/light"
} > requirements-light.txt

echo "[*] Resolving ML additions (.[ml], dry-run report) ..."
"$WORK/full/bin/pip" install --dry-run --report "$WORK/ml.json" --quiet ".[ml]" -c requirements.txt
"$PYTHON" - "$WORK/ml.json" <<'PY'
import json, sys
from packaging.utils import canonicalize_name as canon
report = json.load(open(sys.argv[1]))
full = {canon(line.split("==")[0]) for line in open("requirements.txt")
        if "==" in line and not line.startswith("#")}
additions = {}
for item in report.get("install", []):
    meta = item["metadata"]
    if canon(meta["name"]) != canon("lazyown") and canon(meta["name"]) not in full:
        additions[meta["name"]] = meta["version"]
header = [
    "# LazyOwn optional machine-learning dependencies (pinned).",
    "# Heavy, platform-specific (CUDA wheels on Linux x86-64). Code that uses these",
    "# degrades gracefully when absent. Mirrors pyproject [project.optional-dependencies] ml.",
    "# Regenerated by scripts/regen_locks.sh from pyproject.toml; do not hand-edit.",
    "",
]
lines = [f"{name}=={version}" for name, version in sorted(additions.items(), key=lambda kv: kv[0].lower())]
open("requirements-ml.txt", "w").write("\n".join(header + lines) + "\n")
print(f"[*] requirements-ml.txt: {len(lines)} ML-specific pins")
PY

echo "[+] Locks regenerated. Review 'git diff' before committing."
