shellscript = f'''#!/bin/bash
# autogenerated script by pwntomate {version}
# https://github.com/honze-net/pwntomate
'''

with open('payload.json', 'r') as file:
    config = json.load(file)
    rhost = config.get("rhost")
    domain = config.get("domain")
    dirworlist = config.get("dirworlist") or "/usr/share/wordlists/dirb/common.txt"
    usrwordlist = config.get("usrwordlist") or ""
    dnswordlist = config.get("dnswordlist") or ""

_SECURITY_CONFIG = build_default_config(config)
_REDACTOR = CommandRedactor(_SECURITY_CONFIG)

if os.path.exists(cred_path):
    with open(cred_path, 'r') as file:
        text_cred = file.read().strip()
        array_cred = text_cred.split(":")
        username = array_cred[0]
        password = f" -p '{array_cred[1]}' "
else:
    username = _SECURITY_CONFIG.placeholder_username_marker
    password = ''

if domain:
    adomain = domain.split(".")
    ext = adomain[1] if len(adomain) > 1 else adomain[0]
    nameserver = adomain[0]
else:
    if args.strict_domain:
        raise AttributeError(
            "'domain' is missing from payload.json. Legacy mode (--strict-domain) "
            "requires it to be set; either provide a domain or drop --strict-domain."
        )
    ext = ""
    nameserver = ""


def _build_substitutions(host_addr, port, toolname_value, basedir_value, tunnel=""):
    """Return the non-credential substitution map for a tool template.

    Credentials are deliberately excluded so they only enter the
    command string through :class:`CommandRedactor.render`, which
    guarantees the display copy never contains a real credential
    byte-for-byte.
    """
    is_ssl = "ssl" in (tunnel or "").lower()
    return {
        "s": "s" if is_ssl else "",
        "ssl_flag": " -ssl" if is_ssl else "",
        "outputdir": "{baseoutputdir}/{ip}/{port}/{toolname}",
        "ip": host_addr,
        "port": str(port),
        "domain": domain,
        "ext": ext,
        "nameserver": nameserver,
        "dirworlist": dirworlist,
        "usrwordlist": usrwordlist,
        "dnswordlist": dnswordlist,
        "baseoutputdir": basedir_value,
        "toolname": toolname_value,
    }


cmds = []
displays = []


def _fix_sessions_owner():
    """Best-effort ownership fixup, silent when not permitted.

    Scans run under sudo leave root-owned files behind. Fixed argv only
    (no shell, no user input); ``sudo -n`` never prompts, plain call
    covers operator-owned trees, failure is non-fatal either way.
    """
    for argv in (
        ["sudo", "-n", "chown", "1000:1000", "sessions", "-R"],
        ["chown", "1000:1000", "sessions", "-R"],
    ):
        if subprocess.run(argv, capture_output=True, check=False).returncode == 0:
            break
    for argv in (
        ["sudo", "-n", "chmod", "755", "sessions", "-R"],
        ["chmod", "755", "sessions", "-R"],
    ):
        if subprocess.run(argv, capture_output=True, check=False).returncode == 0:
            break
for host in report.hosts:
    for service in host.services:
        for filename in glob.glob(args.tooldir+"/*.tool"):
            tool = json.load(open(filename, 'r'))
            if tool["active"] and (service.service in tool["trigger"] or 'all' in tool["trigger"]):
                cmd_template = tool["command"]
                toolname = tool.get("toolname", filename)

                if "{domain}" in cmd_template and not domain:
                    print(f"skip {toolname}: needs 'domain' (assign domain <name>)")
                    continue

                tunnel = getattr(service, "tunnel", "") or ""
                base_escaped = args.basedir.replace(" ", r"\ ")
                tool_escaped = tool["toolname"].replace(" ", r"\ ")
                substitutions = _build_substitutions(
                    host.address,
                    service.port,
                    tool_escaped,
                    base_escaped,
                    tunnel,
                )
                cmd, display_cmd = _REDACTOR.render(
                    cmd_template,
                    substitutions,
                    username,
                    password,
                )
                if re.search(r"\{[A-Za-z_]+\}", cmd):
                    print(f"skip {toolname}: template leaves an unresolved placeholder, not running")
                    continue
                print(display_cmd)
                mkdir_cmd = f'mkdir -p {base_escaped}/{host.address}/{service.port}/{tool_escaped}'
                shellscript += mkdir_cmd + '\n'
                shellscript += f'{cmd}\n'
                cmds.append(f'{mkdir_cmd} && {cmd}')
                displays.append(display_cmd)
if args.execute:
    def _run_tool(cmd):
        """Run one auto-job command without shell interpretation.

        Splits the generated ``mkdir -p ... && <tool>`` chain into a
        directory-creation step plus a tool step. The tool step uses
        shlex.split with shell False so scan-derived host data cannot
        inject shell operators. Falls back to shell only for templates
        that contain additional chaining beyond the single mkdir prefix.
        """
        import shlex
        parts = cmd.split(" && ", 1)
        if len(parts) == 2 and parts[0].strip().startswith("mkdir -p "):
            mkdir_argv = shlex.split(parts[0])
            subprocess.run(mkdir_argv, shell=False, capture_output=True, text=True, timeout=30, check=False)
            tool_argv = shlex.split(parts[1])
            return subprocess.run(tool_argv, shell=False, capture_output=True, text=True, timeout=600, check=False)
        return subprocess.run(shlex.split(cmd), shell=False, capture_output=True, text=True, timeout=600, check=False)

    with ThreadPoolExecutor(max_workers=4) as executor:
        futures = {executor.submit(_run_tool, cmd): display for cmd, display in zip(cmds, displays)}
        for future in as_completed(futures):
            try:
                result = future.result()
            except Exception as exc:
                print(f'{futures[future]}\n[tool failed: {exc}]')
                continue
            print(futures[future])
            stdout = (result.stdout or '').strip()
            stderr = (result.stderr or '').strip()
            if stdout:
                print(stdout)
            if stderr:
                print(stderr, file=sys.stderr)
            if result.returncode != 0 and not stdout and not stderr:
                print(f'[exit code {result.returncode}]')
    _fix_sessions_owner()
else:
    print(shellscript)
