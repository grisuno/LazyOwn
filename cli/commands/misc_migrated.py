    @cmd2.with_category("12. Miscellaneous")
    def do_suggest_next(self, line):
        """Suggest next commands by walking the graph from recent activity.

        Usage: ``suggest_next [N]``. Reads ``sessions/LazyOwn_session_report.csv``
        to find recent commands and recommends graph neighbours weighted by
        inverse distance. Pass space-separated command names to override the
        recent history (``suggest_next lazynmap do_ping 7``).

        :param line: optional list of seed commands, optionally followed by
            a numeric limit.
        :type line: str
        :return: None
        """
        import csv as _csv2
        import json as _j

        tokens = (line or "").split()
        if tokens and tokens[-1].isdigit():
            limit  = int(tokens[-1])
            seeds  = tokens[:-1]
        else:
            limit  = 6
            seeds  = tokens

        # Determine phase
        phase     = self.params.get("phase", "") or "recon"
        _palias   = {
            "recon": "recon", "scan": "recon",
            "enum": "enum",
            "exploit": "exploit",
            "privesc": "privesc", "postexp": "postexp",
            "lateral": "lateral",
            "cred": "cred",
            "exfil": "exfil",
            "c2": "c2",
            "report": "report",
        }
        phase_key = _palias.get(phase.lower(), "recon")

        # Commands already run this session
        _seen2: set = set()
        try:
            with open("sessions/LazyOwn_session_report.csv", newline="", errors="ignore") as _fh2:
                for _row2 in _csv2.DictReader(_fh2):
                    _v2 = (_row2.get("tool") or _row2.get("command") or "").strip().split()[0]
                    if _v2:
                        _seen2.add(_v2)
                        _seen2.add(f"do_{_v2}")
        except OSError:
            pass

        # Load command index
        try:
            _idx    = _j.loads(open("cli/command_index.json").read())
            _ptc    = _idx.get("phase_to_commands", {})
            _meta   = {
                e["name"]: e.get("summary", "")
                for e in _idx.get("commands", []) if isinstance(e, dict) and "name" in e
            }
        except Exception:
            _idx  = {}
            _ptc  = {}
            _meta = {}

        # Trigger-matched addons/tools from the latest nmap scan
        _trigger_shown = 0
        try:
            from cli.exploration import ExplorationEngine, resolve_current_os
            _rhost_seed = self.params.get("rhost") or None
            _engine = ExplorationEngine(current_os=resolve_current_os(self.params))
            _ux_addons = _engine.unexplored_addons(_rhost_seed)
            _ux_tools = _engine.unexplored_tools(_rhost_seed)
            _ux_combined: list[tuple[str, str]] = []
            for _a in _ux_addons:
                _ux_combined.append((_a.name, "addon"))
            for _t in _ux_tools:
                _ux_combined.append((_t.name, "tool"))
            if _ux_combined:
                print_msg("Triggered by your scan (never run):")
                for _entry_name, _kind in _ux_combined[:limit]:
                    print_msg(f"  {_entry_name:<26} [{_kind}]")
                    _trigger_shown += 1
        except Exception as _exc:
            print_warn(f"Trigger suggestions unavailable: {_exc}")

        # Use seeds as extra priority if provided
        _shown = _trigger_shown
        if seeds:
            print_msg(f"Suggestions after: {', '.join(seeds)}")
            from cli.reactive_hints import _KILL_CHAIN_NEXT as _KCN
            for _seed in seeds:
                for _next in _KCN.get(_seed, [])[:limit]:
                    if _next not in _seen2:
                        _lbl = _next.replace("do_", "")
                        _sum = _meta.get(f"do_{_next}", _meta.get(_next, ""))[:70]
                        print_msg(f"  {_lbl:<26} {_sum}")
                        _shown += 1
                        if _shown >= limit:
                            break
                if _shown >= limit:
                    break

        if _shown < limit:
            # Phase-priority suggestions not yet run
            _candidates = [
                c for c in _ptc.get(phase_key, [])
                if c not in _seen2 and c.replace("do_", "") not in _seen2
            ]
            if not _candidates:
                # Always useful basics if index empty
                _candidates = ["do_ping", "do_lazynmap", "do_gobuster", "do_enum4linux", "do_searchsploit"]
            if _shown == 0:
                print_msg(f"Suggested next for phase '{phase_key}':")
            for _c in _candidates[:limit - _shown]:
                _lbl = _c.replace("do_", "")
                _sum = _meta.get(_c, "")[:70]
                print_msg(f"  {_lbl:<26} {_sum}")
                _shown += 1

        if _shown == 0:
            print_msg("  All phase commands have been run. Try: recommend_next")

        if not _seen2:
            print_msg("  (No session history yet — start with:  ping  →  lazynmap)")

    @cmd2.with_category("12. Miscellaneous")
    def do_recommend_next(self, line):
        """Recommend the next action via the unified recommendation engine.

        This is the single source of truth for "what next". The engine in
        ``cli/recommendation.py`` fuses every available signal into one ranked
        list with full provenance:

        - **policy** (``skills/lazyown_policy.py``) — learned kill-chain category
          priors that up-weight matching concrete actions.
        - **recon plan** (``cli/recon_plan.py``) — addons/tools/commands whose
          trigger matches services in the latest nmap scan.
        - **graph** (``cli/graph_advisor.py``) — graphify neighbours of your
          recent activity. Requires ``/graphify .`` at least once.
        - **kill-chain** — static adjacency / phase-priority tables.

        Signals whose backend is absent degrade silently. This is the CLI
        equivalent of the MCP tool ``lazyown_recommend_next``.

        Usage:
            ``recommend_next [N]``
        """
        from rich.console import Console as _RC
        from rich.rule import Rule

        from cli.recommendation import KIND_CATEGORY
        from cli.recommendation_signals import build_context, build_default_engine

        c = _RC(highlight=False, soft_wrap=True)
        tokens = (line or "").split()
        limit = int(tokens[0]) if tokens and tokens[0].isdigit() else 5

        engine = build_default_engine(payload=self.params)
        ctx = build_context(self.params, target=self.params.get("rhost") or None, limit=limit)
        recommendations = engine.recommend(ctx)

        if not recommendations:
            print_warn("No recommendations yet.")
            print_msg("Start with 'lazynmap' to generate scan data, then run 'recommend_next' again.")
            return

        c.print(Rule("[bold]Next-best actions[/] (fused: policy + recon + graph + kill-chain)"))
        for i, rec in enumerate(recommendations, 1):
            normalised = min(rec.score, 1.0)
            bar = "█" * int(normalised * 10)
            tag = "category" if rec.kind == KIND_CATEGORY else rec.kind
            sources = ", ".join(rec.sources)
            c.print(
                f"  [bold cyan]{i}.[/] [{bar:<10}] [bold]{rec.action}[/] "
                f"[dim]({tag} · {sources})[/]"
            )
            for reason in rec.reasons:
                c.print(f"       [dim]{reason}[/]")
            if rec.command_preview:
                c.print(f"       [green]$ {rec.command_preview}[/]")
        c.print()

