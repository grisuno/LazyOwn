        test_client, tmp_path = client
        _write_csv_report(tmp_path, [
            {"start": "1735689600.0", "command": "whoami /all", "duration_ms": "50", "destination_ip": "10.0.0.7"},
        ])

        resp = test_client.get("/dashboard/timeline")
