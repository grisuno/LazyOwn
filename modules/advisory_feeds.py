def find_ss(keyword=""):
    """
    Find CVEs in the National Vulnerability Database based on a keyword.

    This function takes a keyword, formats it for the API request,
    and sends a GET request to the NVD API. If the request is successful,
    it returns the JSON response containing CVE data; otherwise,
    it returns False.

    Parameters:
    - keyword (str): The keyword to search for in CVEs.

    Returns:
    - dict or bool: The JSON response containing CVE data or False on failure.
    Thanks to Sicat 🐈
    An excellent tool for CVE detection, I implemented only the keyword search as I had to change some libraries. Soon also for XML generated by nmap :) Total thanks to justakazh. https://github.com/justakazh/sicat/
    """
    keyword = f"{keyword}"
    keyword_encoded = keyword.replace(" ", "%20")
    import shutil as _shutil
    import subprocess as _sp

    curl = _shutil.which("curl")
    if curl:
        try:
            result = _sp.run(
                [
                    curl,
                    "-sS",
                    "--connect-timeout",
                    "5",
                    "--max-time",
                    "12",
                    f"https://services.nvd.nist.gov/rest/json/cves/2.0?keywordSearch={keyword_encoded}",
                ],
                capture_output=True,
                text=True,
                timeout=15,
            )
            if result.returncode == 0 and result.stdout.strip():
                import json as _json

                return _json.loads(result.stdout)
            return False
        except (_sp.TimeoutExpired, Exception):
            return False
    try:
        resp = requests.get(
            f"https://services.nvd.nist.gov/rest/json/cves/2.0?keywordSearch={keyword_encoded}", timeout=(3, 8)
        )
        if resp.status_code == 200:
            return resp.json()
        else:
            return False
    except requests.exceptions.Timeout:
        print_error("NVD API request timed out")
        return False
    except requests.exceptions.RequestException as exc:
        print_error(f"NVD API request failed: {exc}")
        return False


