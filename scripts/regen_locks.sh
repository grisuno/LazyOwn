#!/usr/bin/env bash
# Regenerate the LazyOwn dependency lock files from pyproject.toml via uv.
#
# pyproject.toml is the single source of truth. `uv lock` resolves the whole
# dependency graph into uv.lock (cross-platform, hash-pinned). The
# requirements*.txt files are exported projections of that lock so pip-only
# consumers (Docker, install.sh) keep working with identical versions.
#
#   uv.lock                 authoritative cross-platform lock
#   requirements.txt        full core export (.[analytics,ai,cloud,rag])
#   requirements-light.txt  base-only export
#   requirements-ml.txt     .[ml] additions on top of the full export
#
# Usage: bash scripts/regen_locks.sh
# Requires the uv binary (pip install uv or the standalone installer).

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

if ! command -v uv >/dev/null 2>&1; then
    for candidate in "$HOME/.local/bin"; do
        if [[ -x "$candidate/uv" ]]; then
            PATH="$candidate:$PATH"
            break
        fi
    done
fi
if ! command -v uv >/dev/null 2>&1; then
    echo "[!] uv not found. Install it: pip install uv" >&2
    exit 1
fi

echo "[*] Resolving the full dependency graph (uv lock) ..."
uv lock

echo "[*] Exporting requirements.txt (full core: .[analytics,ai,cloud,rag], no ml/dev tooling) ..."
uv export --all-extras --no-emit-project --no-dev --no-extra ml --no-extra dev \
    --output-file requirements.txt

echo "[*] Exporting requirements-light.txt (base only) ..."
uv export --no-extra analytics --no-extra ai --no-extra cloud --no-extra rag --no-extra ml \
    --no-emit-project --no-dev \
    --output-file requirements-light.txt

echo "[*] Exporting requirements-ml.txt (.[ml] direct pins) ..."
uv export --all-extras --no-emit-project --no-dev \
    --output-file "$ROOT/.uv-export-full.tmp"
python3 - > requirements-ml.txt <<'PY'
import tomllib

with open("pyproject.toml", "rb") as handle:
    pyproject = tomllib.load(handle)

ml_names = list((pyproject["project"]["optional-dependencies"].get("ml") or []))
pins = []
for raw in open(".uv-export-full.tmp"):
    line = raw.strip()
    if not line or line.startswith("#") or line.startswith("--hash"):
        continue
    if "==" not in line:
        continue
    name = line.split("==")[0].strip()
    if name in ml_names:
        pins.append(line.split(" \\")[0].strip())

header = [
    "# LazyOwn optional machine-learning dependencies (pinned).",
    "# Heavy, platform-specific (CUDA wheels on Linux x86-64). Code that uses these",
    "# degrades gracefully when absent. Mirrors pyproject [project.optional-dependencies] ml.",
    "# Regenerated by scripts/regen_locks.sh from pyproject.toml; do not hand-edit.",
    "",
]
seen = []
for pin in pins:
    if pin.split("==")[0] not in [s.split("==")[0] for s in seen]:
        seen.append(pin)
print("\n".join(header + seen).rstrip() + "\n")
PY
rm -f "$ROOT/.uv-export-full.tmp"

echo "[*] Exporting requirements-dev.txt (dev extra, hash-pinned) ..."
uv export --no-emit-project --extra dev \
    --output-file requirements-dev.txt
printf '\n' >> requirements-dev.txt

echo "[+] Locks regenerated: uv.lock, requirements.txt, requirements-light.txt, requirements-ml.txt, requirements-dev.txt."
echo "    Review 'git diff' before committing."
